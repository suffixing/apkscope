#!/usr/bin/env python3
"""Import the Exodus Privacy tracker list into a generated Rust module.

Input:  trackers.json — the Exodus tracker export (schema: {"trackers": {id: {...}}}).
        Canonical source is https://reports.exodus-privacy.eu.org/api/trackers (ODbL 1.0,
        API key required); this script also accepts the TrackerControl mirror of the
        same list (https://raw.githubusercontent.com/TrackerControl/tracker-control-android/
        master/app/src/main/assets/trackers.json), which adds an `id` field.

Output: src/fingerprint/exodus.rs — `pub(super) const TRACKERS: &[ExodusTracker]`.

Matching semantics preserved from exodus_core's static_analysis.py:
  - code_signature: an UNANCHORED regex over slash-form class names (com/facebook/x/...);
    the `.` in dot-form signatures doubles as a wildcard that also matches `/`. No
    signature in the list uses real metacharacters (verified), so each alternative is
    converted to slash form here (`.` -> `/`, trailing `.` dropped) and matched as a
    package prefix; alternatives that are not plain package paths (leading `.`,
    uppercase) are flagged `scan` and matched with a substring scan instead.
  - signatures with length <= 3 are skipped (their engine does the same).
  - network_signature: hostname regex, kept raw; the Rust side unescapes `\\.` and
    only compiles a real regex when metacharacters remain. Matched against DEX and
    native-lib strings as corroborating evidence (Exodus itself uses these for traffic
    analysis only).

Run from the repo root:
    python3 scripts/exodus_import.py scripts/exodus/trackers.json src/fingerprint/exodus.rs
"""
import json
import re
import sys
from datetime import date

EXODUS_CAT = {  # Exodus category -> our Category enum variant
    "Analytics": "Analytics",
    "Advertisement": "Ads",
    "Location": "Analytics",
    "Profiling": "Analytics",
    "Identification": "Auth",
    "Crash reporting": "Crash",
}


def rust_str(s: str) -> str:
    return json.dumps(s)  # JSON escaping is valid Rust string escaping for our data


def to_slash_alt(alt: str) -> tuple[str, bool] | None:
    """Convert one dot-form alternative to slash form.

    Returns (slash_form, needs_scan) or None when the alternative can never match a
    class name (it contains characters that never occur in one, e.g. `-` or spaces).
    """
    alt = alt.strip()
    if not alt:
        return None
    # a plain package path: [A-Za-z0-9_.$] with `.` as separator; a leading `.` or any
    # uppercase letter makes it a class-name fragment (Exodus matches those unanchored)
    if not re.fullmatch(r"[A-Za-z0-9_.$]+", alt):
        return None  # real metacharacters or impossible characters: never matches
    needs_scan = alt.startswith(".") or any(c.isupper() for c in alt)
    slash = alt.replace(".", "/").strip("/")
    return (slash, needs_scan)


def main() -> None:
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, encoding="utf-8") as f:
        data = json.load(f)["trackers"]

    rows = []
    skipped_sigs = skipped_alts = 0
    for key in sorted(data, key=lambda k: int(k)):
        t = data[key]
        code = t["code_signature"].strip()
        net = t["network_signature"].strip()
        if len(code) <= 3:
            skipped_sigs += 1
            continue
        alts = []
        scan = False
        for alt in code.split("|"):
            match to_slash_alt(alt):
                case (slash, needs_scan):
                    alts.append(slash)
                    scan |= needs_scan
                case None:
                    if alt.strip():
                        skipped_alts += 1
        if not alts:
            skipped_sigs += 1
            continue
        cats = [EXODUS_CAT.get(c, "Analytics") for c in t["categories"]]
        rows.append({
            "id": t.get("id", int(key)),
            "name": t["name"].strip(),
            "cat": cats[0] if cats else "Analytics",
            "alts": alts,
            "scan": scan,
            "net": net,
        })

    out = []
    w = out.append
    w("//! GENERATED FILE — Exodus Privacy tracker list. DO NOT EDIT BY HAND.")
    w("//!")
    w("//! Source: https://reports.exodus-privacy.eu.org/api/trackers (ODbL 1.0).")
    w("//! Generated by scripts/exodus_import.py from the Exodus export (via the")
    w("//! TrackerControl mirror when the live API is unreachable). Any redistribution")
    w("//! of this list must keep the ODbL 1.0 attribution: (c) Exodus Privacy contributors,")
    w(f"//! https://exodus-privacy.eu.org — snapshot taken {date.today().isoformat()}.")
    w("//!")
    w("//! Matching follows exodus_core's static analysis: unanchored match of each")
    w("//! code signature against slash-form class names, the dot also matching `/`;")
    w("//! signatures of length <= 3 are skipped. Alternatives are stored in slash form;")
    w("//! plain package paths match as prefixes, `scan` entries (class-name fragments)")
    w("//! match as substrings. Network signatures are matched against DEX and native-lib")
    w("//! strings as corroborating evidence (Exodus itself uses them for traffic analysis")
    w("//! only).")
    w("")
    w("use super::Category;")
    w("")
    w("/// One Exodus tracker: slash-form code-signature alternatives plus its host pattern.")
    w("pub(super) struct ExodusTracker {")
    w("    /// Exodus numeric id, kept for cross-referencing their reports")
    w("    pub id: u32,")
    w("    pub name: &'static str,")
    w("    pub cat: Category,")
    w("    /// slash-form alternatives (`com/facebook/login`); a package path matches any")
    w("    /// class under it")
    w("    pub alts: &'static [&'static str],")
    w("    /// some alternative is a class-name fragment, not a package path: match those")
    w("    /// with a substring scan over class names")
    w("    pub scan: bool,")
    w("    /// network signature, raw (hostname regex; `\\\\.` is unescaped before use)")
    w("    pub net: &'static str,")
    w("}")
    w("")
    w(f"pub(super) const TRACKERS: &[ExodusTracker] = &[")
    for r in rows:
        alts = ", ".join(rust_str(a) for a in r["alts"])
        w(f"    ExodusTracker {{ id: {r['id']}, name: {rust_str(r['name'])}, cat: Category::{r['cat']}, alts: &[{alts}], scan: {'true' if r['scan'] else 'false'}, net: {rust_str(r['net'])} }},")
    w("];")
    w("")
    w(f"// {len(rows)} trackers imported; {skipped_sigs} entries and {skipped_alts} alternatives")
    w("// skipped (empty, <= 3 chars, or characters that cannot occur in a class name).")
    text = "\n".join(out) + "\n"
    with open(dst, "w", encoding="utf-8") as f:
        f.write(text)
    scans = sum(1 for r in rows if r["scan"])
    nets = sum(1 for r in rows if r["net"])
    print(f"wrote {dst}: {len(rows)} trackers ({scans} needing substring scan, "
          f"{nets} with network signatures); skipped {skipped_sigs} sigs / {skipped_alts} alts")


if __name__ == "__main__":
    main()
